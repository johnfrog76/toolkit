// Regenerates src/shared/wordmarkPaths.ts: "ToolKit" set in Inter Bold as
// outlines, and every face the app's logo knows (src/shared/faces.ts) as an
// outline of its glyph, so the wordmark draws with no font. Run by hand when
// the word, the weight, the tracking or the faces change, never at build or
// in a test run:
//
//   node tests/outline-wordmark.mjs <path to Inter's variable font .ttf>
//
// Inter is under the SIL Open Font License 1.1 (THIRD-PARTY-NOTICES.md); the
// font file itself is not in this tree, only the outlines it produced.
import fs from "node:fs";
import path from "node:path";
import * as fontkit from "fontkit";

const WORD = "ToolKit";
const EM = 100;
const TRACKING = -0.04 * EM;
const VARIATION = { wght: 700, opsz: 32 };
// A glyph the font lacks is drawn with this one instead.
const FALLBACK = { "━": "—" };

const file = process.argv[2];
if (!file) {
  console.error("usage: node tests/outline-wordmark.mjs <Inter[opsz,wght].ttf>");
  process.exit(2);
}
const font = fontkit.openSync(file).getVariation(VARIATION);
const k = EM / font.unitsPerEm;
const round = (s) => s.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 100) / 100));

// The letters, in a row, baseline at y=0.
const run = font.layout(WORD);
let x = 0;
const letters = run.glyphs.map((g, i) => {
  const pos = run.positions[i];
  const d = round(
    g.path
      .scale(k, -k)
      .translate(x + pos.xOffset * k, 0)
      .toSVG(),
  );
  x += pos.xAdvance * k + TRACKING;
  return { char: WORD[i], d };
});
const width = Math.round((x - TRACKING) * 100) / 100;

// The faces: each glyph at its face's size, centred on its own box at the
// origin; the component puts it under the o's and turns it.
const facesSource = fs.readFileSync(
  path.resolve(import.meta.dirname, "..", "src", "shared", "faces.ts"),
  "utf8",
);
const faceRe =
  /id: "([a-z]+)",\s*name: "([^"]+)",\s*light: \{ content: "(.+?)", fontSize: "(\d+)%", rotate: "(-?\d+)deg"[^}]*\},\s*dark: \{ content: "(.+?)", fontSize: "(\d+)%", rotate: "(-?\d+)deg"/g;
const outline = (ch, pct) => {
  const char = FALLBACK[ch] ?? ch;
  const cp = char.codePointAt(0);
  if (!font.hasGlyphForCodePoint(cp)) throw new Error(`no glyph for ${JSON.stringify(ch)}`);
  const g = font.glyphForCodePoint(cp);
  const s = (k * pct) / 100;
  const b = g.bbox;
  const cx = ((b.minX + b.maxX) / 2) * s;
  const cy = -((b.minY + b.maxY) / 2) * s;
  return round(g.path.scale(s, -s).translate(-cx, -cy).toSVG());
};
const faces = [];
for (const m of facesSource.matchAll(faceRe)) {
  const [, id, name, lc, lp, lr, dc, dp, dr] = m;
  faces.push({
    id,
    name,
    light: { d: outline(lc, Number(lp)), rotate: Number(lr) },
    dark: { d: outline(dc, Number(dp)), rotate: Number(dr) },
  });
}
if (faces.length === 0) throw new Error("no faces read from faces.ts");

const face = (f) => `  {
    id: ${JSON.stringify(f.id)},
    name: ${JSON.stringify(f.name)},
    light: { d: ${JSON.stringify(f.light.d)}, rotate: ${f.light.rotate} },
    dark: { d: ${JSON.stringify(f.dark.d)}, rotate: ${f.dark.rotate} },
  }`;
const out = `// The wordmark's letters as outlines: "ToolKit" set in Inter Bold (SIL Open
// Font License 1.1), optical size 32, tracked -0.04em, in a 100-unit em with
// the baseline at y=0; and every face of src/shared/faces.ts as an outline of
// its glyph at the face's size, centred on its own box at the origin.
// Generated by web/tests/outline-wordmark.mjs from the font file; nothing
// here is typed by hand. The mark draws with no font.

/** The advance of the whole word, in em units (100 = the em). */
export const WORDMARK_WIDTH = ${width};

/** Each letter's outline, in order. */
export const WORDMARK_LETTERS: readonly { char: string; d: string }[] = [
${letters.map((l) => `  { char: ${JSON.stringify(l.char)}, d: ${JSON.stringify(l.d)} }`).join(",\n")}
];

/** One face's drawing for a theme: the outline, and the turn it is drawn with. */
export interface WordmarkFaceShape {
  d: string;
  rotate: number;
}

/** Every face, by the id the app's logo preference stores. */
export const WORDMARK_FACES: readonly {
  id: string;
  name: string;
  light: WordmarkFaceShape;
  dark: WordmarkFaceShape;
}[] = [
${faces.map(face).join(",\n")},
];
`;
const target = path.resolve(import.meta.dirname, "..", "src", "shared", "wordmarkPaths.ts");
fs.writeFileSync(target, out);
console.log(
  `${WORD}: ${letters.length} letters, width ${width}; ${faces.length} faces -> ${path.relative(process.cwd(), target)}`,
);
