import { render, screen } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router";
import { ReviewPage } from "./ReviewPage";

// One h1 per page: the header's title. The review's body opens with a note and
// then its own title, which the real viewer must not draw as a second h1.
jest.mock("./api.ado", () => ({
  useGetReviewPreviewQuery: () => ({
    data: { files: [] },
    isLoading: false,
    isFetching: false,
    isError: false,
    refetch: jest.fn(),
  }),
  useGetReviewDetailQuery: () => ({
    data: {
      folder: "2026-04-01_2026-04-30",
      period: "2026-04-01 – 2026-04-30",
      title: "April work review",
      content: "> Generated by the scaffold.\n\n# April work review\n\n## One\nx\n",
      path: "/hub/reviews/2026/2026-04-01_2026-04-30/review.md",
    },
    isLoading: false,
    isFetching: false,
  }),
  useRunCommandMutation: () => [jest.fn(), { isLoading: false }],
}));

it("a review whose body opens with a note then its title has exactly one h1", () => {
  render(
    <MemoryRouter initialEntries={["/review/2026-04-01_2026-04-30"]}>
      <Routes>
        <Route path="/review/:folder" element={<ReviewPage />} />
      </Routes>
    </MemoryRouter>,
  );
  expect(screen.getAllByRole("heading", { level: 1 })).toHaveLength(1);
});
